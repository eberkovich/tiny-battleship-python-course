# Куры и овцы
#
# На ферме живут только куры и овцы. У каждой курицы 2 ноги, у каждой овцы 4.
# Известно общее количество животных и общее количество ног. Нужно выяснить,
# сколько на ферме кур и сколько овец.
#
# Напиши программу, которая получает два целых числа: сначала количество
# животных, затем количество ног. Преобразуй оба ответа в числа. Выведи два
# количества на отдельных строках: сначала кур, затем овец, без подписей.
#
# Для проверки вручную можно взять 8 животных и 22 ноги. Это только данные для
# одного запуска, не числа для записи в код: программа должна работать и с
# другими подходящими ответами. Животных не меньше одного; ответы всегда
# соответствуют возможному количеству кур и овец. Проверять их правильность не
# нужно.
#
# Сам придумай, как определить оба количества. На ферме могут быть только куры
# или только овцы: тогда количество другого вида равно 0. Если трудно начать,
# нарисуй животных или воспользуйся подсказкой.
