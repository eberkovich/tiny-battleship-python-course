# Проект. Покупка и сдача
#
# Напиши программу-кассу для магазина «Всевозможные волшебные вредилки». В
# магазине три товара:
#
# Удлинители ушей
# 17 сиклей за штуку
# Забастовочные завтраки
# 23 сикля за коробку
# Карликовые пушистики
# 31 сикль за пушистика
#
# Первая часть — покупки и чек.
#
# Сначала задай покупателю три вопроса: сколько он покупает удлинителей ушей,
# затем сколько коробок забастовочных завтраков, затем сколько карликовых
# пушистиков. Каждый ответ — целое число от 0 до 100. Ноль означает, что этот
# товар не покупают.
#
# Рассчитай стоимость каждого вида товара и общую стоимость покупки. Для чека
# достаточно вывести числа в четырёх строках:
#
# - Первая строка — количество удлинителей ушей и их стоимость в сиклях.
# - Вторая строка — количество коробок забастовочных завтраков и их стоимость
#   в сиклях.
# - Третья строка — количество карликовых пушистиков и их стоимость в сиклях.
# - Четвёртая строка — только общая стоимость покупки в сиклях.
#
# В первых трёх строках раздели два числа пробелом. Названия товаров, слово
# «сикли» и подпись «Итого» писать не нужно. Если товар не покупают, покажи для
# него два нуля.
#
# Пример оформления: покупатель выбрал 4 удлинителя ушей, 0 коробок завтраков
# и 2 пушистика. Чек выглядит так:
#
# 4 68
# 0 0
# 2 62
# 130
#
# Вторая часть — оплата и сдача.
#
# Продолжи ту же программу. Только после чека спроси, сколько галлеонов
# покупатель даёт для оплаты, затем сколько сиклей, затем сколько кнатов. Это
# три новых ответа: целые числа не меньше нуля. Деньги отдаются вместе, за всю
# покупку. Их точно хватит; проверять это не нужно.
#
# Рассчитай сдачу. Выдай как можно больше галлеонов, затем как можно больше
# сиклей, а остаток — кнатами.
#
# Покажи сдачу одной строкой из трёх чисел через пробел: количество галлеонов,
# затем сиклей, затем кнатов. Слово «Сдача» и названия монет писать не нужно.
# Если каких-то монет нет, покажи 0.
#
# Пример оформления: если сдача составила 2 галлеона, 5 сиклей и 0 кнатов,
# строка выглядит так:
#
# 2 5 0
#
# Оба примера показывают только оформление. Твоя программа должна рассчитывать
# числа для каждой покупки. Если захочешь добавить подписи, можно написать их
# своими словами: проверка оценивает числа, их порядок и момент вывода, а не
# написание слов. Вопросы покупателю тоже можно формулировать своими словами.
#
# В одном запуске программа получает шесть ответов: три о покупках, затем три
# об оплате. Чек появляется до вопросов об оплате, а сдача — после всех
# ответов. Программа должна работать с разными покупками и оплатой, а не
# только с одним выбранным примером.
#
# Для начала можно написать первую часть и запустить её, чтобы посмотреть чек.
# Проверка пока не засчитает проект целиком: для этого нужно закончить обе
# части в одном файле.

