# Смешная история
#
# Сделай программу, которая собирает короткую историю из ответов человека.
# Получи три ответа в таком порядке:
#
# - кто герой истории — имя или название, например «робот»;
# - как называется место действия — например «Лунная база»;
# - что герой умеет делать — действие, например «есть печенье».
#
# Сначала получи и сохрани все ответы. Потом выведи историю из трёх строк по
# этому шаблону:
#
# - В месте под названием <место> появился герой: <герой>
# - <герой> объявляет: моя суперсила — <действие>
# - Теперь <место> ждёт новых приключений!
#
# Угловые скобки не выводи: на их месте должны быть ответы человека. Между
# частями каждой строки оставляй один пробел. Заметь: герой и место нужны в
# истории больше одного раза, но спрашивать их повторно не надо.
#
# Сам выбери имена переменных и составь программу. Не меняй файл между
# вопросами. После первого запуска попроси кого-нибудь придумать другие ответы
# и прочитай новую историю.
